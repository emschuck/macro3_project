# Country-name helper.
# The constants file should define country_names. If a label is missing,
# return the ISO3 code so plots and tables still work.
get_country_name <- function(code) {
  out <- country_names |>
    filter(iso3c == code) |>
    pull(country)

  if (length(out) == 0 || is.na(out[1])) {
    return(code)
  }

  out[1]
}

