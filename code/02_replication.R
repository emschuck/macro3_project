extract_weights_for_country <- function(result) {
  result$tables$tab.w |>
    as.data.frame() |>
    transmute(
      treated_iso3c = result$treated_iso3c,
      donor_iso3c = as.character(unit.names),
      donor_weight = as.numeric(w.weights)
    )
}

make_export_for_country <- function(result, data, vars_to_export) {

  treated_code <- result$treated_iso3c
  treated_name <- result$country_name

  weights_i <- extract_weights_for_country(result)

  treated_actual <- data |>
    filter(
      iso3c == treated_code,
      year %in% plot_period
    ) |>
    select(
      iso3c,
      country,
      year,
      all_of(vars_to_export)
    ) |>
    pivot_longer(
      cols = all_of(vars_to_export),
      names_to = "variable",
      values_to = "value"
    ) |>
    mutate(
      treated_iso3c = treated_code,
      treated_country = treated_name,
      unit_type = "treated_actual",
      donor_iso3c = NA_character_,
      donor_country = NA_character_,
      donor_weight = NA_real_
    ) |>
    select(
      treated_iso3c,
      treated_country,
      unit_type,
      iso3c,
      country,
      year,
      variable,
      value,
      donor_iso3c,
      donor_country,
      donor_weight
    )

  donor_real <- data |>
    filter(
      iso3c %in% weights_i$donor_iso3c,
      year %in% plot_period
    ) |>
    select(
      iso3c,
      country,
      year,
      all_of(vars_to_export)
    ) |>
    left_join(
      weights_i,
      by = c("iso3c" = "donor_iso3c")
    ) |>
    pivot_longer(
      cols = all_of(vars_to_export),
      names_to = "variable",
      values_to = "value"
    ) |>
    mutate(
      treated_country = treated_name,
      unit_type = "donor_real",
      donor_iso3c = iso3c,
      donor_country = country
    ) |>
    select(
      treated_iso3c,
      treated_country,
      unit_type,
      iso3c,
      country,
      year,
      variable,
      value,
      donor_iso3c,
      donor_country,
      donor_weight
    )

  synthetic_values <- donor_real |>
    group_by(
      treated_iso3c,
      treated_country,
      year,
      variable
    ) |>
    summarise(
      value = ifelse(
        all(is.na(value)),
        NA_real_,
        sum(donor_weight * value, na.rm = TRUE)
      ),
      .groups = "drop"
    ) |>
    mutate(
      unit_type = "synthetic",
      iso3c = paste0("SYN_", treated_code),
      country = paste("Synthetic", treated_name),
      donor_iso3c = NA_character_,
      donor_country = NA_character_,
      donor_weight = NA_real_
    ) |>
    select(
      treated_iso3c,
      treated_country,
      unit_type,
      iso3c,
      country,
      year,
      variable,
      value,
      donor_iso3c,
      donor_country,
      donor_weight
    )

  bind_rows(
    treated_actual,
    synthetic_values,
    donor_real
  )
}

