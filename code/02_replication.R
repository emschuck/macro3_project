run_scm_country <- function(treated_iso3c) {

  message("Running SCM for ", treated_iso3c)

  country_name_treated <- get_country_name(treated_iso3c)

  treated_id <- country_ids$unit_id[
    country_ids$iso3c == treated_iso3c
  ]

  if (length(treated_id) == 0) {
    stop("Treated country not found in country_ids: ", treated_iso3c)
  }

  control_ids_i <- country_ids$unit_id[
    country_ids$iso3c %in% donor_countries &
      !(country_ids$unit_id %in% bad_controls)
  ]

  if (length(control_ids_i) == 0) {
    stop("No usable donor countries available for ", treated_iso3c)
  }

  dataprep.out <- dataprep(
    foo = scm_df,
    predictors = scm_predictors_active,
    predictors.op = "mean",
    dependent = outcome_var,
    unit.variable = "unit_id",
    unit.names.variable = "unit_name",
    time.variable = "year",
    treatment.identifier = treated_id,
    controls.identifier = control_ids_i,
    time.predictors.prior = pre_period,
    time.optimize.ssr = pre_period,
    time.plot = plot_period,
    special.predictors = lapply(
      special_years_scm,
      function(y) list(special_var, y, c("mean"))
    )
  )

  synth.out <- synth(
    data.prep.obj = dataprep.out
  )

  synth.tables <- synth.tab(
    dataprep.res = dataprep.out,
    synth.res = synth.out
  )

  # Save path plot.
  png(
    paste0("output/figures/scm_path_", treated_iso3c, ".png"),
    width = 900,
    height = 600
  )

  path.plot(
    synth.res = synth.out,
    dataprep.res = dataprep.out,
    tr.intake = treatment_year,
    Ylab = paste0("GDP per capita: ", country_name_treated),
    Xlab = "Year",
    Legend = c(
      country_name_treated,
      paste("Synthetic", country_name_treated)
    ),
    Legend.position = "topleft"
  )

  dev.off()

  # Save gap plot.
  png(
    paste0("output/figures/scm_gap_", treated_iso3c, ".png"),
    width = 900,
    height = 600
  )

  gaps.plot(
    synth.res = synth.out,
    dataprep.res = dataprep.out,
    tr.intake = treatment_year,
    Ylab = paste0("Gap in GDP per capita: ", country_name_treated),
    Xlab = "Year"
  )

  dev.off()

  write.csv(
    synth.tables$tab.w,
    paste0("output/tables/scm_weights_", treated_iso3c, ".csv"),
    row.names = FALSE
  )

  write.csv(
    synth.tables$tab.pred,
    paste0("output/tables/scm_predictor_balance_", treated_iso3c, ".csv"),
    row.names = TRUE
  )

  list(
    treated_iso3c = treated_iso3c,
    country_name = country_name_treated,
    dataprep = dataprep.out,
    synth = synth.out,
    tables = synth.tables
  )
}

